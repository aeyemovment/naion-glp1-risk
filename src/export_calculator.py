"""Calculator v2 export (app_v2/; separate from the v1 calculator cited in the medRxiv preprint, which stays in app/): core ensemble (XGBoost + L2 logistic regression, mean of probabilities) plus optional,
literature-based patient-level modifiers. Uses the released v1.0.0 weights in models/ (no re-fitting).

Core inputs (required): GLP-1RA drug, comparator, indication, age, time horizon -> PubMed-only models.
Optional modifiers: only the factors selected in Stage 18 (forward selection by AUROC gain); published patient-level ratios, applied on the log-odds scale and centred on the average
covariate level of the training cohorts, so an input left as "unknown" contributes 0 and the core estimate is unchanged:
    contribution = ln(OR) * (x - p_ref)          binary items
    contribution = ln(OR_k) - sum_j p_j ln(OR_j) categorical items (cup-to-disc ratio)
The modifiers were NOT learned or validated in the reconstructed data (no patient-level covariates exist there);
they assume independence of factors and use unadjusted pooled ratios. research_prototype=true;
compliance_ref=Addendum_5_DT9. NOT for clinical, diagnostic, treatment-selection or regulatory use.
"""
import os, json, re, math, numpy as np, pandas as pd, xgboost as xgb
import sys; sys.path.insert(0, "src")
from common import ipd, X_all, COLS

co = pd.read_json("data/extracted/cohort_level.json")
ref = lambda c: float(co.groupby(co.source_pmid.astype(str))[c].max().median()) / 100   # median across studies reporting it

# Published ratios: Liu 2021 meta-analysis (PMID 34671609); Disc-at-Risk Study (PMID 42556433). Same values as Stage 12.
MODIFIERS = [
    {"id": "sex", "label": "Sex", "type": "binary", "yes": "Male", "no": "Female", "or": 1.67, "p_ref": 1 - ref("pct_female_exposed"),
     "source": "Liu 2021 meta-analysis, PMID 34671609 (male vs female)"},
    {"id": "htn", "label": "Hypertension", "type": "binary", "or": 1.28, "p_ref": ref("pct_hypertension"), "source": "PMID 34671609"},
    {"id": "hld", "label": "Hyperlipidaemia", "type": "binary", "or": 1.43, "p_ref": ref("pct_hyperlipidemia"), "source": "PMID 34671609"},
    {"id": "chd", "label": "Coronary heart disease", "type": "binary", "or": 1.68, "p_ref": ref("pct_cvd"), "source": "PMID 34671609"},
    {"id": "osa", "label": "Obstructive sleep apnea", "type": "binary", "or": 3.28, "p_ref": ref("pct_osa"), "source": "PMID 34671609 (RR used as OR)"},
    {"id": "cdr", "label": "Cup-to-disc ratio", "type": "categorical",
     "levels": [{"v": "le020", "label": "0.20 or less", "or": 46.3, "p": 0.09}, {"v": "021_040", "label": "0.21 to 0.40", "or": 6.8, "p": 0.47},
                {"v": "gt040", "label": "Greater than 0.40", "or": 1.0, "p": 0.44}],
     "source": "Disc-at-Risk Study, PMID 42556433 (fellow eye measured after NAION; case-control OR vs > 0.40)"},
]
SEL = {"cup_to_disc": "cdr", "sleep_apnoea": "osa", "male_sex": "sex", "hypertension": "htn", "hyperlipidaemia": "hld", "coronary_heart_disease": "chd"}
S18 = json.load(open("results/stage18/summary.json")); FS = pd.read_csv("results/stage18/forward_selection.csv")
selected = {SEL[k] for k in S18["selected"]}
for m in MODIFIERS:
    r = FS[FS.factor.map(SEL) == m["id"]].iloc[0]; m["selected"] = m["id"] in selected
    m["auroc_gain_alone"] = round(float(r.alone_gain), 4); m["auroc_gain_marginal"] = round(float(r.marginal_gain), 4); m["selection_step"] = int(r.step)
for m in MODIFIERS:
    if m["type"] == "binary": m["p_ref"] = round(m["p_ref"], 3)
    else: m["center"] = sum(l["p"] * math.log(l["or"]) for l in m["levels"])

lr = json.load(open("models/logreg_pubmed_only.json"))
assert lr["columns"] == COLS
bst = xgb.Booster(); bst.load_model("models/xgb_pubmed_only.json")
p_x = bst.predict(xgb.DMatrix(X_all[COLS]))
z = lr["intercept"] + ((X_all[COLS].to_numpy() - np.array(lr["mu"])) / np.array(lr["sd"])) @ np.array(lr["coef"])
p_l = 1 / (1 + np.exp(-z)); p_e = (p_x + p_l) / 2
w = ipd.n.to_numpy(); o = np.argsort(p_e); cw = np.cumsum(w[o]) / w.sum()
ens_thr = float(p_e[o][np.searchsorted(cw, 0.90)])

js = open("app/model.js").read()
obj = json.loads(re.search(r"window\.NAION_MODEL = (\{.*\});", js, re.S).group(1))
obj["lr"] = {k: lr[k] for k in ("mu", "sd", "coef", "intercept")}
obj["spec"]["ensemble_top10_threshold"] = ens_thr
obj["modifiers"] = [m for m in MODIFIERS if m["selected"]]
obj["flags"]["version"] = "2.0.0"
os.makedirs("app_v2", exist_ok=True)
open("app_v2/model.js", "w").write("// Calculator v2 - auto-generated by src/export_models.py + src/export_calculator.py - PubMed-only XGBoost + logistic regression "
                                "ensemble with literature-based optional modifiers (research prototype; NOT for clinical use)\n"
                                f"window.NAION_MODEL = {json.dumps(obj, separators=(',', ':'))};\n")
pd.DataFrame([{"Factor": m["label"], "Level": l["label"] if m["type"] != "binary" else (m.get("yes", "Yes")), "OR": l["or"] if m["type"] != "binary" else m["or"],
               "Reference level in training cohorts": (f"{100*l['p']:.0f}% of controls" if m["type"] != "binary" else f"{100*m['p_ref']:.0f}%"), "Source": m["source"], "AUROC gain alone": m["auroc_gain_alone"],
               "Forward-selection step": m["selection_step"], "Marginal AUROC gain": m["auroc_gain_marginal"], "In calculator v2": "Yes" if m["selected"] else "No"}
              for m in MODIFIERS for l in (m.get("levels") or [None])]).to_csv("results/calculator_modifiers.csv", index=False)
# parity vectors for the JS ensemble
test = [{"x": X_all[COLS].iloc[i].tolist(), "p_xgb": float(p_x[i]), "p_lr": float(p_l[i])} for i in range(0, len(X_all), max(1, len(X_all) // 25))]
json.dump(test, open("models/js_test_vectors_ensemble.json", "w"))
print("ensemble top10 threshold", ens_thr, "\n", pd.read_csv("results/calculator_modifiers.csv").to_string(index=False))
