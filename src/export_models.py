"""Export final PubMed-only models (trained on ALL reconstructed data) as release weights + a browser model for the calculator.
Outputs: models/{xgb_pubmed_only.json, xgb_pubmed_only.ubj, logreg_pubmed_only.json, rf_pubmed_only.joblib, MODEL_CARD.md}
         app/model.js (compact XGBoost trees for client-side inference) and models/js_test_vectors.json (parity check).
research_prototype=true; compliance_ref=Addendum_5_DT9. NOT for clinical, diagnostic or treatment-selection use.
"""
import os, json, itertools, joblib, datetime as dt
import numpy as np, pandas as pd
import sys; sys.path.insert(0, "src")
from common import ipd, fit, X_all, COLS, MU, SD
os.makedirs("models", exist_ok=True); os.makedirs("app", exist_ok=True)
FLAGS = {"research_prototype": True, "synthetic_only": False, "compliance_ref": "Addendum_5_DT9", "not_for_clinical_use": True,
         "version": "1.0.0", "trained_on": "all 3,271,499 reconstructed patients (1,425 events), 11 cohorts", "date": str(dt.date.today())}
S1 = json.load(open("results/stage1/stage1_results.json"))
xgb, lr, rf = fit("xgb", ipd), fit("logreg", ipd), fit("rf", ipd)
xgb.get_booster().save_model("models/xgb_pubmed_only.json"); xgb.get_booster().save_model("models/xgb_pubmed_only.ubj")
json.dump({"columns": COLS, "mu": MU.tolist(), "sd": SD.tolist(), "coef": lr.coef_[0].tolist(), "intercept": float(lr.intercept_[0]), **FLAGS},
          open("models/logreg_pubmed_only.json", "w"), indent=1)
joblib.dump(rf, "models/rf_pubmed_only.joblib", compress=3)

# ---- compact trees for JS
trees = []
for t in json.loads(xgb.get_booster().save_raw("json"))["learner"]["gradient_booster"]["model"]["trees"]:
    trees.append({"l": t["left_children"], "r": t["right_children"], "f": t["split_indices"], "c": t["split_conditions"], "d": t["default_left"]})
cfg = json.loads(xgb.get_booster().save_config())
bs = float(str(cfg["learner"]["learner_model_param"]["base_score"]).strip("[]"))
REF = {"region": "us", "source_type": "ehr_network", "outcome_def": "naion"}
med = {"pct_female": float(np.average(ipd.pct_female, weights=ipd.n))}
rng = {c: [float(ipd[c].min()), float(ipd[c].max())] for c in ["mean_age", "followup_years", "pct_female"]}
spec = {"columns": COLS, "reference_setting": REF, "pct_female_default": med["pct_female"], "training_ranges": rng,
        "therapies": {"semaglutide": 1, "glp1ra_class": 1, "sema_or_tirz": 1, "no_glp1ra": 0, "sglt2i": 0, "dpp4i": 0, "other_antidiabetic": 0, "other_antiobesity": 0},
        "indications": ["t2d", "obesity", "iih"]}
def row(therapy, ind, age, fu):
    x = dict.fromkeys(COLS, 0.0)
    for k, v in {"therapy": therapy, "indication": ind, **REF}.items(): x[f"{k}_{v}"] = 1.0
    x.update(glp1ra_exposed=float(spec["therapies"][therapy]), followup_years=fu, mean_age=age, pct_female=med["pct_female"])
    return [x[c] for c in COLS]
grid = list(itertools.product(spec["therapies"], spec["indications"], [45, 55, 62], [1, 2, 5]))
Xg = pd.DataFrame([row(*g) for g in grid], columns=COLS)
pg = xgb.predict_proba(Xg)[:, 1]
ptr = xgb.predict_proba(X_all)[:, 1]; o = np.argsort(ptr); cw = np.cumsum(ipd.n.to_numpy()[o]) / ipd.n.sum()
spec["top10_threshold"] = float(ptr[o][np.searchsorted(cw, 0.90)]); spec["prevalence"] = float(np.average(ipd.y, weights=ipd.n))
json.dump([{"input": list(g), "p": float(p)} for g, p in zip(grid, pg)], open("models/js_test_vectors.json", "w"))
perf = {"auroc_holdout_10_90": S1["holdout_10_90"]["xgb"]["auroc"] if "xgb" in S1["holdout_10_90"] else None,
        "kfold": S1["kfold_summary"].get("xgb") if isinstance(S1["kfold_summary"], dict) else None, "loso": S1["loso_summary"].get("xgb") if isinstance(S1["loso_summary"], dict) else None}
js = ("// Auto-generated by src/export_models.py - PubMed-only XGBoost (research prototype; NOT for clinical use)\n"
      f"window.NAION_MODEL = {json.dumps({'base_score': bs, 'trees': trees, 'spec': spec, 'perf': perf, 'flags': FLAGS}, separators=(',', ':'))};\n")
open("app/model.js", "w").write(js)
card = f"""# Model card - NAION risk in GLP-1RA users (PubMed-only models) v1.0.0

**Research prototype. NOT for clinical, diagnostic, treatment-selection or regulatory use.** compliance_ref=Addendum_5_DT9.\n\nCopyright (c) 2026 NeuroAgent AI, Inc. Research use only, with attribution; no commercial use without written permission. Licence: NAION-GLP1 Research-Only Non-Commercial License (see LICENSE).

- Training data: count-weighted pseudo-individual data reconstructed from 11 published cohorts (3,271,499 patients; 1,425 NAION/ION events). No patient-level health records were used.
- Features ({len(COLS)} columns): {', '.join(COLS)}. Values are arm- or study-level (ecological), not individual measurements.
- Files: `xgb_pubmed_only.json/.ubj` (XGBoost 300 trees, depth 3, lr 0.05; load with `xgboost.Booster().load_model`),
  `logreg_pubmed_only.json` (L2 logistic regression on standardized features: p = sigmoid(intercept + coef . (x - mu)/sd)), `rf_pubmed_only.joblib` (scikit-learn RF).
- Validation (from the paper): XGBoost AUROC 0.656 +/- 0.011 over ten disjoint 10% training folds; leave-one-study-out AUROC ~0.53; PPV at top-10% threshold ~0.087% vs prevalence 0.044%.
- Known limitations: discrimination is driven mainly by study setting; transport to unseen settings is near chance; individual-level risk factors (cup-to-disc ratio, sleep apnoea, hypertension) are absent.
- Intended use: research enrichment and hypothesis generation only.
"""
open("models/MODEL_CARD.md", "w").write(card)
print("base_score", bs, "trees", len(trees), "pred range", pg.min(), pg.max()); print(os.popen("du -sh models/* app/model.js").read())
